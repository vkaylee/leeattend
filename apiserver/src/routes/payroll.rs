use axum::{
    routing::{delete, get, post},
    Router,
};
use std::sync::Arc;

use crate::handlers;
use crate::AppState;

pub fn router() -> Router<Arc<AppState>> {
    Router::new()
        .route(
            "/workspaces/:ws_id/payroll-settings",
            get(handlers::get_payroll_settings).patch(handlers::update_payroll_settings),
        )
        .route(
            "/workspaces/:ws_id/payroll-settings/history",
            get(handlers::get_payroll_settings_history),
        )
        .route(
            "/workspaces/:ws_id/salary-components",
            get(handlers::get_salary_components).post(handlers::create_salary_component),
        )
        .route(
            "/workspaces/:ws_id/employments/:id/salary-components",
            get(handlers::get_employment_salary_components)
                .post(handlers::assign_employment_salary_component),
        )
        .route(
            "/workspaces/:ws_id/employees/:id/payslips",
            get(handlers::get_employee_payslips),
        )
        .route(
            "/workspaces/:ws_id/employees/:id/calculate-payroll",
            post(handlers::calculate_payroll),
        )
        .route(
            "/workspaces/:ws_id/payroll/calculate-batch",
            post(handlers::calculate_batch_payroll),
        )
        .route(
            "/workspaces/:ws_id/payroll/payslips",
            get(handlers::get_workspace_payslips),
        )
        .route(
            "/workspaces/:ws_id/payroll/incentive-policies",
            get(handlers::get_incentive_policies).post(handlers::create_incentive_policy),
        )
        .route(
            "/workspaces/:ws_id/payroll/incentive-policies/:policy_id",
            delete(handlers::delete_incentive_policy),
        )
        .route(
            "/workspaces/:ws_id/payroll/incentive-policies/:policy_id/clone",
            post(handlers::clone_incentive_policy),
        )
        .route(
            "/workspaces/:ws_id/employees/:id/payroll-config",
            post(handlers::set_employee_payroll_config).get(handlers::get_employee_payroll_configs),
        )
        // Overtime policies
        .route(
            "/workspaces/:ws_id/overtime/policies",
            get(handlers::list_policies).post(handlers::create_policy),
        )
        .route(
            "/workspaces/:ws_id/overtime/policies/:policy_id",
            get(handlers::get_policy),
        )
        .route(
            "/workspaces/:ws_id/overtime/policies/:policy_id/rules",
            post(handlers::add_rule),
        )
        .route(
            "/workspaces/:ws_id/overtime/policies/assign",
            post(handlers::assign_policy),
        )
        // Overtime Requests
        .route(
            "/workspaces/:ws_id/overtime/requests",
            get(handlers::overtime_request::list_ot_requests)
                .post(handlers::overtime_request::create_ot_request),
        )
        .route(
            "/workspaces/:ws_id/overtime/requests/:id",
            get(handlers::overtime_request::get_ot_request),
        )
        .route(
            "/workspaces/:ws_id/overtime/requests/:id/submit",
            post(handlers::overtime_request::submit_for_approval),
        )
        .route(
            "/workspaces/:ws_id/overtime/requests/:id/consent/:emp_id",
            post(handlers::overtime_request::employee_consent),
        )
        .route(
            "/workspaces/:ws_id/overtime/requests/behalf-assignments",
            get(handlers::overtime_request::list_request_behalf_assignments)
                .post(handlers::overtime_request::create_request_behalf_assignment),
        )
        .route(
            "/workspaces/:ws_id/overtime/requests/behalf-assignments/my-targets",
            get(handlers::overtime_request::get_my_request_behalf_targets),
        )
        .route(
            "/workspaces/:ws_id/overtime/requests/behalf-assignments/:id",
            delete(handlers::overtime_request::delete_request_behalf_assignment),
        )
}
