import { Eye, EyeOff } from 'lucide-react';
import React, { useState } from 'react';
import { useTranslation } from 'react-i18next';
import Button from "@/components/ui/button";
import { Typography } from "@/components/ui/typography";
import { useDateTimeFormatter } from '@/hooks/use-datetime';
import { Employee, IncentiveEvaluationResult, Organization, Payslip } from '@/lib/api/types';

import { EarningsBreakdown } from './payslip/earnings-breakdown';
import { EmployeeDetails } from './payslip/employee-details';
import { PayslipHeader } from './payslip/payslip-header';
import { PayslipTotals } from './payslip/payslip-totals';

interface PayslipDocumentProps {
  employee: Employee;
  payslip: Payslip;
  organization: Organization | null;
}

export default function PayslipDocument({ employee, payslip, organization }: PayslipDocumentProps) {
  const { t } = useTranslation();
  const [isMasked, setIsMasked] = useState(false);
  const { formatMonthYear, formatDate } = useDateTimeFormatter();
  const currencyFormatter = new Intl.NumberFormat('vi-VN', {
    style: 'currency',
    currency: 'VND',
    minimumFractionDigits: 0,
  });

  const formatAmount = (value: string | number) => {
    if (isMasked) return "•••••• ₫";
    return currencyFormatter.format(typeof value === 'string' ? parseFloat(value) : value);
  };

  const totalIncentives = payslip.incentives?.reduce((accumulator: number, inc: IncentiveEvaluationResult) => accumulator + parseFloat(inc.amount), 0) ?? 0;
  const grossPay = parseFloat(payslip.base_pay_amount) + parseFloat(payslip.overtime_pay_amount) + totalIncentives;

  return (
    <div className='bg-white dark:bg-slate-900 p-8 md:p-16 max-w-[210mm] mx-auto shadow-sm print:shadow-none print:p-0 text-slate-700 dark:text-slate-200 font-sans' data-testid="payslip-document" id='payslip-document'>
      <div className="flex justify-end pb-4 print:hidden">
        <Button
          aria-label={isMasked ? "Hiển thị số tiền" : "Ẩn số tiền bảo mật"}
          className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium rounded-xl text-slate-600 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors border border-slate-200 dark:border-slate-700 h-auto"
          onClick={() => setIsMasked(!isMasked)}
          type="button"
          variant="outline"
        >
          {isMasked ? <Eye size={14} /> : <EyeOff size={14} />}
          <span>{isMasked ? t("common.show_amount", "Hiện số tiền") : t("common.mask_amount", "Bảo mật số tiền")}</span>
        </Button>
      </div>
      <PayslipHeader formatDate={formatDate} formatMonthYear={formatMonthYear} organization={organization} payslip={payslip} t={t} />
      <EmployeeDetails employee={employee} formatAmount={formatAmount} payslip={payslip} t={t} />

      <div className='space-y-8' data-testid="earnings-breakdown">
        <EarningsBreakdown formatAmount={formatAmount} payslip={payslip} />
        <PayslipTotals formatAmount={formatAmount} grossPay={grossPay} payslip={payslip} />
      </div>

      <footer className='mt-20 pt-10 border-t border-slate-50 dark:border-slate-800 text-center space-y-2 opacity-50 print:opacity-100' data-testid="payslip-footer">
        <Typography className='text-[9px] font-bold uppercase tracking-[0.5em] text-slate-500 dark:text-slate-400' variant="p">Generated by LeeAttend System</Typography>
        <Typography className='text-[8px] font-bold text-slate-300 dark:text-slate-600 tracking-widest' variant="p">{new Date().toISOString()}</Typography>
      </footer>
    </div>
  );
}